export const TRANSLATIONS: Record<UILanguage, TranslationDictionary> = {
  en,
  ar,
  ur,
  id,
  tr,
};

export function isUILanguage(value: unknown): value is UILanguage {
  return (
    value === 'en' ||
    value === 'ar' ||
    value === 'ur' ||
    value === 'id' ||
    value === 'tr'
  );
}

export function getTranslationDictionary(
  lang: UILanguage
): TranslationDictionary {
  return Object.hasOwn(TRANSLATIONS, lang) ? TRANSLATIONS[lang] : TRANSLATIONS.en;
}

export function translate(lang: UILanguage, key: TranslationKey): string {
  const dict = getTranslationDictionary(lang);
  if (Object.hasOwn(dict, key)) {
    return dict[key];
  }
  return Object.hasOwn(TRANSLATIONS.en, key) ? TRANSLATIONS.en[key] : '';
}
